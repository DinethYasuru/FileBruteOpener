#!/usr/bin/env node
/* Regenerates js/samples-data.js: base64 copies of samples/* embedded directly into a JS file,
 * so the dashboard's "Pre-generated sample" loader works even when index.html is opened
 * directly via file:// (no fetch() of a sibling file needed - browsers block that over
 * file://, which is the whole reason this script exists instead of just fetching samples/
 * at runtime). Run this again whenever a file under samples/ changes.
 *
 * Usage: node local-service/embed-samples.js   (run from the repo root or anywhere; paths
 * below are resolved relative to this script's own location, not the current directory)
 */
const fs = require('fs');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const files = {
  pdf: 'samples/sample.pdf',
  zip: 'samples/sample.zip',
  rar: 'samples/sample.rar',
  '7z': 'samples/sample.7z',
  docx: 'samples/sample-office.docx',
  xlsx: 'samples/sample-office.xlsx',
  pptx: 'samples/sample-office.pptx',
  gpg: 'samples/sample.gpg',
};

let out = '/* Auto-generated by local-service/embed-samples.js - DO NOT EDIT BY HAND.\n';
out += '   Base64 copies of samples/* so the Pre-generated sample loader works even when\n';
out += '   index.html is opened directly via file:// (no fetch() needed - browsers block\n';
out += '   fetch() of sibling files over file://, see README/app.js for details).\n';
out += '   Regenerate with: node local-service/embed-samples.js */\n\n';
out += 'const SAMPLE_DATA_B64 = {\n';
for (const [key, rel] of Object.entries(files)) {
  const b64 = fs.readFileSync(path.join(repoRoot, rel)).toString('base64');
  out += `  ${JSON.stringify(key)}: ${JSON.stringify(b64)},\n`;
}
out += '};\n\n';
out += 'function base64ToBytes(b64) {\n';
out += '  const bin = atob(b64);\n';
out += '  const bytes = new Uint8Array(bin.length);\n';
out += '  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);\n';
out += '  return bytes;\n';
out += '}\n\n';
out += 'if (typeof module !== "undefined") {\n';
out += '  module.exports = { SAMPLE_DATA_B64, base64ToBytes };\n';
out += '}\n';

const outPath = path.join(repoRoot, 'js', 'samples-data.js');
fs.writeFileSync(outPath, out);
console.log(`Wrote ${outPath} (${fs.statSync(outPath).size} bytes) from ${Object.keys(files).length} sample files.`);
